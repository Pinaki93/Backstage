package dev.pinaki.backstage.library;

import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.concurrent.CopyOnWriteArrayList;

/** Exposes an application's key-value store to Backstage. */
public abstract class KeyValueController extends BasicController {
    private final String title;
    private final CopyOnWriteArrayList<EntriesCallback> callbacks =
            new CopyOnWriteArrayList<>();
    private volatile Map<String, String> entries = Collections.emptyMap();

    /**
     * @param source registers a callback that the application invokes with a complete snapshot
     *               initially and whenever its backing store changes
     */
    protected KeyValueController(String title, String path, EntriesSource source) {
        super(path);
        if (title == null || title.trim().isEmpty()) {
            throw new IllegalArgumentException("title must not be blank");
        }
        if ("/".equals(path)) throw new IllegalArgumentException("path must not be /");
        if (source == null) throw new IllegalArgumentException("source must not be null");
        this.title = title;
        source.subscribe(this::publish);
    }

    public final String getTitle() {
        return title;
    }

    /** Returns the most recently emitted snapshot. */
    public final Map<String, String> getEntries() {
        return entries;
    }

    /** Key-value pages are generated by the implementation and do not use a raw resource. */
    @Override
    public final int getHtmlResource() {
        return 0;
    }

    /** Observes snapshots until the returned subscription is closed. */
    public final Subscription observe(EntriesCallback callback) {
        if (callback == null) throw new IllegalArgumentException("callback must not be null");
        callbacks.add(callback);
        callback.onChanged(entries);
        return () -> callbacks.remove(callback);
    }

    private void publish(Map<String, String> newEntries) {
        if (newEntries == null) throw new IllegalArgumentException("entries must not be null");
        entries = Collections.unmodifiableMap(new LinkedHashMap<>(newEntries));
        for (EntriesCallback callback : callbacks) callback.onChanged(entries);
    }

    public abstract void create(String key, String value);
    public abstract void update(String key, String value);
    public abstract void delete(String key);
    public abstract void clear();

    public interface EntriesSource {
        void subscribe(EntriesCallback callback);
    }

    public interface EntriesCallback {
        void onChanged(Map<String, String> entries);
    }

    public interface Subscription extends AutoCloseable {
        @Override
        void close();
    }
}
